let currentLocale: Locale = 'ja';

export function getLocale(): Locale {
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  if (!translations[locale]) return;
  currentLocale = locale;
  document.documentElement.setAttribute('lang', locale === 'ja' ? 'ja' : 'en');
  document.dispatchEvent(new CustomEvent('localechange', { detail: locale }));
}

export function getLocales(): Record<Locale, LocaleInfo> {
  return locales;
}

export function t(str: string): string {
  if (currentLocale === 'ja') return str;
  return translations.en[str] || str;
}
