import { describe, expect, it } from 'vitest';
import { shouldCreateNotification, stableNotificationDocumentId } from '../src/notificationDomain';

describe('notification identity', () => {
  it('suppresses notifications generated by an action on oneself', () => {
    expect(shouldCreateNotification({ fromUserId: 'same-user', userId: 'same-user' })).toBe(false);
    expect(shouldCreateNotification({ fromUserId: 'actor', userId: 'recipient' })).toBe(true);
  });

  it('maps one SNS event to one deterministic notification document', () => {
    const event = { type: 'like', fromUserId: 'actor', userId: 'recipient', eventId: 'like:event/1' };
    const first = stableNotificationDocumentId(event);
    expect(stableNotificationDocumentId(event)).toBe(first);
    expect(first).not.toContain(':');
    expect(stableNotificationDocumentId({ ...event, eventId: 'like:event/2' })).not.toBe(first);
    expect(stableNotificationDocumentId({ ...event, eventId: undefined })).toBe('');
  });
});
